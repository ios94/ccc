import Foundation

/// Translate an Arabic UI string to the in-app language.
func AL(_ arabic: String) -> String {
	AshteStrings.translate(arabic)
}

/// Same as AL, for strings with percent-at placeholders.
func ALf(_ arabic: String, _ args: String...) -> String {
	let format = AshteStrings.translate(arabic)
	return String(format: format, arguments: args.map { NSString(string: $0) })
}

enum AshteStrings {
	static func translate(_ arabic: String) -> String {
		switch AshteL10n.current {
		case "en": return english[arabic] ?? arabic
		case "ckb": return kurdish[arabic] ?? arabic
		default: return arabic
		}
	}

